import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = resolve(import.meta.dirname, "../../../contracts/out");
const target = resolve(import.meta.dirname, "../src/abi.ts");

export const CONTRACTS = [
  ["channelHubAbi", "ChannelHub"],
  ["chessRulesAbi", "ChessRules"],
  ["mockUsdcAbi", "MockUSDC"],
] as const;

export function readAbi(name: string): unknown {
  return JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8")).abi;
}

export function renderAbiModule(): string {
  const body = CONTRACTS.map(
    ([exportName, contract]) => `export const ${exportName} = ${JSON.stringify(readAbi(contract), null, 2)} as const;\n`,
  ).join("\n");
  return `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit; run \`pnpm --filter @arena/sdk abi\`.\n\n${body}`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(target, renderAbiModule());
  console.log(`wrote ${target}`);
}
