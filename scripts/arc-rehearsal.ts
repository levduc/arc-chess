/** Every address whose balance this run moves: the deployer, both wallets and every session key so far. */
function systemAddresses(): Address[] {
  const out = new Set<Address>([DEPLOYER]);
  for (const n of NAMES) {
    const w = state.homes[n].wallet;
    if (w) out.add(w);
    for (const id of channelIdsOf(n)) {
      const r = recordOf(n, id);
      if (r) out.add(r.signers[r.me]);
    }
  }
  return [...out];
}

/** Controller ruling: the run stops once gas spent passes 2 USDC. Every USDC of the run is in these addresses or
 *  escrowed in one of the run's channels (fees go back to the deployer, the hub's fee recipient). */
async function gasGuard(where: string): Promise<void> {
  if (!state.deployerBefore) return;
  let total = 0n;
  for (const a of systemAddresses()) total += await nativeBalance(a);
  for (const ch of Object.values(state.channels)) {
    if (!ch?.id) continue;
    const id = ch.id;
    const info = (await read(() => pub.readContract({ address: HUB, abi: channelHubAbi, functionName: "channelInfo", args: [id] }))) as { phase: number; funded: readonly [boolean, boolean] };
    if (info.phase < 1 || info.phase > 3) continue; // None, Finalized, Reclaimed: nothing escrowed
    const params = (await read(() => pub.readContract({ address: HUB, abi: channelHubAbi, functionName: "channelParams", args: [id] }))) as { deposit: bigint; feePerPlayer: bigint };
    const funded = BigInt(info.funded.filter(Boolean).length);
    total += funded * (params.deposit + params.feePerPlayer) * WEI_PER_UNIT;
  }
  const spent = BigInt(state.deployerBefore) - total;
  progress("gas guard", { where, spentWei: spent, spentUsdc: formatUnits(spent, 18) });
  if (spent > GAS_STOP_WEI) throw new Error(`STOP: gas spent so far is ${formatUnits(spent, 18)} USDC, over the 2 USDC budget`);
}

// ------------------------------------------------------------------------------------------------ games

const turnOf = async (p: Player, id: Hex) => Number((await status(p, id)).turnNum);

/** One move by `mover`; returns once `other` holds it. A rate-limited answer counts if the turn moved on. */
async function moveAndWait(mover: Player, other: Player, id: Hex, move: string, opts: { offerDraw?: boolean; ms?: number } = {}): Promise<number> {
  const before = await turnOf(mover, id);
  const t0 = Date.now();
  await act(mover, "/move", { move, channel: id, ...(opts.offerDraw ? { offerDraw: true } : {}) }, async () => (await turnOf(mover, id)) > before, move);
  await waitStatus(other, id, (s) => Number(s.turnNum) > before || s.gameStatus !== "playing", opts.ms ?? 90_000, `${move} (after turn ${before})`);
  return Date.now() - t0;
}

/**
 * Plays `line` for the game that started at channel turn `startTurn`, from wherever it stands (a rerun resumes it):
 * each move by whichever side is on move, waiting for the other side to hold it. Returns each latency.
 */
async function playFrom(a: Player, b: Player, id: Hex, line: string[], startTurn: number, opts: { upTo?: number; ms?: number } = {}): Promise<number[]> {
  const out: number[] = [];
  const stop = opts.upTo ?? line.length;
  for (;;) {
    const sa = await status(a, id);
    const i = Number(sa.turnNum) - startTurn;
    if (i >= stop || sa.gameStatus !== "playing") return out;
    const [mover, other] = sa.myTurn ? [a, b] : [b, a];
    out.push(await moveAndWait(mover, other, id, line[i], { ms: opts.ms }));
  }
}

/** The winner's player index for a finished game, from one side's status. */
function winnerOf(s: Status): number | null {
  if (s.gameStatus === "draw") return null;
  const winnerColor = s.gameStatus === "white_won" ? "white" : "black";
  return s.color === winnerColor ? s.me : 1 - s.me;
}

async function waitGameOver(a: Player, b: Player, id: Hex, want: Status["gameStatus"], ms = 90_000): Promise<Status> {
  const sa = await waitStatus(a, id, (s) => s.gameStatus === want, ms, `game over (${want})`);
  await waitStatus(b, id, (s) => s.gameStatus === want && s.turnNum === sa.turnNum, ms, `game over (${want}) at turn ${sa.turnNum}`);
  return status(a, id);
}

/** The NEW_GAME handshake from game `g` to `g + 1` (resumes a half-done one); returns game `g + 1`'s start turn. */
async function nextGame(a: Player, b: Player, id: Hex, g: number): Promise<number> {
  const started = (s: Status) => s.gameIndex === g + 1 && s.newGame === "none";
  if (!started(await status(a, id))) {
    if ((await status(a, id)).newGame !== "proposed_by_me" && (await status(b, id)).attention !== "new-game-proposed") {
      await act(a, "/next-game", { channel: id }, async () => (await status(a, id)).newGame === "proposed_by_me", `propose game ${g + 1}`);
    }
    await waitStatus(b, id, (s) => s.attention === "new-game-proposed" || started(s), 90_000, "new-game-proposed");
    if (!started(await status(b, id))) {
      await act(b, "/next-game", { channel: id }, async () => started(await status(b, id)), `countersign game ${g + 1}`);
    }
  }
  const sa = await waitStatus(a, id, started, 90_000, `game ${g + 1} started`);
  await waitStatus(b, id, started, 90_000, `game ${g + 1} started`);
  return Number(sa.turnNum);
}

/** Alice offers, Bob accepts; returns once both daemons see the channel Open. */
async function openChannel(ch: ChannelState, kind: ChannelKind, challengeTimeout: bigint): Promise<Hex> {
  const alice = player("alice");
  const bob = player("bob");
  if (ch.offerId && !ch.id) throw new Error(`${kind}: offer ${ch.offerId} was posted by an earlier run but no channel recorded: settle it by hand`);
  if (!ch.id) {
    const before = new Set(channelIdsOf("bob"));
    const t0 = Date.now();
    const { offerId } = (await apiOnce(alice, "POST", "/offers", {
      deposit: DEPOSIT.toString(),
      stakePerGame: STAKE.toString(),
      challengeTimeout: challengeTimeout.toString(),
    })) as { offerId: Hex };
    ch.offerId = offerId;
    save();
    await apiOnce(bob, "POST", "/offers/accept", { offerId });
    const id = await waitFor(`bob's ${kind} channel`, 120_000, async () => channelIdsOf("bob").find((c) => !before.has(c)), 1_000);
    ch.id = id;
    save();
    progress("channel matched", { kind, channelId: id, offerId });
    await waitStatus(alice, id, (s) => s.phase === "Open", 300_000, "Open");
    await waitStatus(bob, id, (s) => s.phase === "Open", 300_000, "Open");
    measure(`${kind}: offer -> Open on both daemons`, Date.now() - t0);
  }
  return ch.id;
}

async function closeBoth(a: Player, b: Player, id: Hex, kind: string, ms = 180_000): Promise<void> {
  const t0 = Date.now();
  // Each sub-step's wall-clock offset from t0, so a slow close can be placed (the first run's XMTP close took 48.9 s).
  const marks: string[] = [];
  const mark = (what: string) => marks.push(`${what} +${((Date.now() - t0) / 1000).toFixed(1)}s`);
  if ((await phaseOf(id)) !== "Finalized") {
    const st = await status(a, id);
    if (!st.closing) await act(a, "/close", { channel: id }, async () => (await status(a, id)).closing, "close (alice)");
    mark("alice /close answered");
    await waitStatus(b, id, (s) => s.opponentWantsToClose === true || s.phase === "Finalized", ms, "opponentWantsToClose");
    mark("bob sees opponentWantsToClose");
    const sb = await status(b, id);
    if (!sb.closing && sb.phase !== "Finalized") {
      await act(b, "/close", { channel: id }, async () => (await status(b, id)).closing || (await phaseOf(id)) === "Finalized", "close (bob)");
    }
    mark("bob /close answered");
    await waitFor(`${kind}: Finalized on chain`, ms, async () => (await phaseOf(id)) === "Finalized", 1_000);
    mark("Finalized on chain (polled every 1 s)");
  }
  await waitStatus(a, id, (s) => s.phase === "Finalized", ms, "Finalized");
  await waitStatus(b, id, (s) => s.phase === "Finalized", ms, "Finalized");
  mark("both daemons Finalized");
  measure(`${kind}: close requested -> Finalized`, Date.now() - t0, marks.join("; "));
}

/** Strictly sequential channels: both session keys swept (true or "dust") before anything else happens. */
async function waitSwept(id: Hex, kind: string): Promise<void> {
  const t0 = Date.now();
  for (const n of NAMES) {
    const r = await waitFor(`${n}'s ${kind} session key swept`, 900_000, async () => {
      const rec = recordOf(n, id);
      return rec?.swept !== undefined ? rec : undefined;
    }, 2_000);
    progress("swept", { kind, name: n, swept: r.swept, sweeps: r.sweeps?.map((x) => ({ amount: x.amount, tx: x.tx })) });
    if (r.swept === "abandoned") state.channels[kind as ChannelKind]?.notes.push(`${n}'s sweep was abandoned`);
  }
  measure(`${kind}: Finalized -> both session keys swept`, Date.now() - t0);
}

function expectFor(id: Hex, deltaA: bigint, ch: ChannelState): void {
  ch.expectedA = (DEPOSIT + deltaA).toString();
  ch.expectedB = (DEPOSIT - deltaA).toString();
  save();
  progress("expected payout", { channelId: id, participant0: ch.expectedA, participant1: ch.expectedB });
}

async function noteErrors(id: Hex, kind: string): Promise<void> {
  for (const n of NAMES) {
    const s = await status(player(n), id);
    if (s.lastError) {
      state.channels[kind as ChannelKind]?.notes.push(`${n}'s lastError: ${s.lastError}`);
      progress("lastError", { kind, name: n, lastError: s.lastError });
    }
  }
}

// ---------------------------------------------------------------------------------------------- channels

const sum = (xs: number[]) => xs.reduce((a, b) => a + b, 0);

async function channelNormal(): Promise<void> {
  const ch = (state.channels.normal ??= { startedAt: new Date().toISOString(), notes: [] });
  const alice = player("alice");
  const bob = player("bob");
  const id = await openChannel(ch, "normal", NORMAL_TIMEOUT);
  ch.games ??= [];
  ch.gameStart ??= { 0: 0 };
  save();
  const recordGame = async (g: number, want: Status["gameStatus"]) => {
    const s = await waitGameOver(alice, bob, id, want);
    ch.games!.push({ gameIndex: g, result: s.gameStatus, winner: winnerOf(s) });
    save();
  };

  // Game 0: white (participant 0) mates in 4 (scholar's mate).
  if (!ch.games.some((g) => g.gameIndex === 0)) {
    const t = await playFrom(alice, bob, id, SCHOLARS_MATE, ch.gameStart[0]);
    measure("normal: game 0 scholar's mate over the relay (sum of moves played this run)", sum(t), `per move ms: ${t.join(", ")}`);
    await recordGame(0, "white_won");
  }
  // Game 1: colours swap; black (participant 0 again) mates in 2 (fool's mate).
  if (!ch.games.some((g) => g.gameIndex === 1)) {
    if (ch.gameStart[1] === undefined) {
      const t0 = Date.now();
      ch.gameStart[1] = await nextGame(alice, bob, id, 0);
      save();
      measure("normal: next-game handshake 0 -> 1", Date.now() - t0);
    }
    const t = await playFrom(alice, bob, id, FOOLS_MATE, ch.gameStart[1]);
    measure("normal: game 1 fool's mate over the relay (sum)", sum(t), `per move ms: ${t.join(", ")}`);
    await recordGame(1, "black_won");
  }
  // Game 2: a draw by agreement on the first move.
  if (!ch.games.some((g) => g.gameIndex === 2)) {
    if (ch.gameStart[2] === undefined) {
      const t0 = Date.now();
      ch.gameStart[2] = await nextGame(alice, bob, id, 1);
      save();
      measure("normal: next-game handshake 1 -> 2", Date.now() - t0);
    }
    const t0 = Date.now();
    const sa = await status(alice, id);
    const [mover, other] = sa.myTurn ? [alice, bob] : [bob, alice];
    if (sa.gameStatus === "playing" && Number(sa.turnNum) === ch.gameStart[2]) {
      await act(mover, "/move", { move: "e2e4", channel: id, offerDraw: true }, async () => (await turnOf(mover, id)) > ch.gameStart![2], "e4 with a draw offer");
    }
    const so = await waitStatus(other, id, (s) => s.gameStatus === "draw_offered" || s.gameStatus === "draw", 90_000, "draw_offered");
    if (so.gameStatus === "draw_offered") {
      await act(other, "/accept-draw", { channel: id }, async () => (await status(other, id)).gameStatus === "draw", "accept the draw");
    }
    await recordGame(2, "draw");
    measure("normal: game 2 e4 with a draw offer -> accepted", Date.now() - t0);
  }

  let deltaA = 0n;
  for (const g of ch.games) if (g.winner !== null) deltaA += g.winner === 0 ? STAKE : -STAKE;
  expectFor(id, deltaA, ch);

  await closeBoth(alice, bob, id, "normal");
  await noteErrors(id, "normal");
  await waitSwept(id, "normal");
  ch.done = true;
  save();
}

async function channelDispute(): Promise<void> {
  const ch = (state.channels.dispute ??= { startedAt: new Date().toISOString(), notes: [] });
  const alice = player("alice");
  const bob = player("bob");
  if (!ch.id) ch.notes.push("challengeTimeout 300 s (testnet only; both homes init-ed with --min-challenge-timeout 300)");
  const id = await openChannel(ch, "dispute", DISPUTE_TIMEOUT);
  const stage = (s: string) => {
    ch.stage = s;
    save();
    progress("dispute stage", { stage: s });
  };

  // Alice (white in game 0) plays e4, then challenges while Bob is on move.
  if (!ch.stage) {
    await playFrom(alice, bob, id, ["e2e4"], 0);
    const t0 = Date.now();
    await act(alice, "/challenge", { channel: id }, async () => (await phaseOf(id)) === "Challenged", "alice's challenge");
    measure("dispute: alice POST /challenge (tx sent and mined)", Date.now() - t0);
    await waitFor("Challenged on chain", 120_000, async () => (await phaseOf(id)) === "Challenged", 2_000);
    await waitStatus(bob, id, (s) => s.phase === "Challenged" && s.challenge?.mustMove === true, 120_000, "bob mustMove");
    measure("dispute: alice's challenge -> bob sees mustMove", Date.now() - t0);
    stage("alice-challenged");
  }
  // Bob answers with a move: his daemon submits it with respond().
  if (ch.stage === "alice-challenged") {
    const t0 = Date.now();
    if ((await turnOf(bob, id)) < 2) await act(bob, "/move", { move: "e7e5", channel: id }, async () => (await turnOf(bob, id)) >= 2, "bob's answering move");
    await waitFor("Open again on chain (responded)", 180_000, async () => (await phaseOf(id)) === "Open", 2_000);
    measure("dispute: bob's move -> respond mined (Open on chain)", Date.now() - t0);
    await waitStatus(alice, id, (s) => s.phase === "Open" && s.turnNum === "2" && s.myTurn, 120_000, "alice back to Open, on move");
    await waitStatus(bob, id, (s) => s.phase === "Open" && s.turnNum === "2", 120_000, "bob back to Open");
    stage("bob-responded");
  }
  // Bob challenges the same (registered) state; Alice is on move and does not move: the watchtower times it out.
  if (ch.stage === "bob-responded") {
    const t0 = Date.now();
    await act(bob, "/challenge", { channel: id }, async () => (await phaseOf(id)) === "Challenged", "bob's challenge");
    measure("dispute: bob POST /challenge (tx sent and mined)", Date.now() - t0);
    await waitFor("Challenged on chain (second)", 120_000, async () => (await phaseOf(id)) === "Challenged", 2_000);
    stage("bob-challenged");
  }
  if (ch.stage === "bob-challenged") {
    const t0 = Date.now();
    if ((await phaseOf(id)) === "Challenged") {
      const sa = await waitStatus(alice, id, (s) => s.phase === "Challenged" && s.challenge?.mustMove === true, 120_000, "alice mustMove");
      progress("dispute: waiting for the timeout", { deadline: sa.challenge?.deadline, secondsLeft: sa.challenge?.secondsLeft });
      ch.notes.push(`second challenge: chain deadline ${sa.challenge?.deadline}, ${sa.challenge?.secondsLeft} s left when alice saw it`);
      save();
    }
    await waitFor("Finalized on chain (timeout)", (Number(DISPUTE_TIMEOUT) + 600) * 1_000, async () => (await phaseOf(id)) === "Finalized", 5_000);
    measure("dispute: alice sees the second challenge -> Finalized by timeout", Date.now() - t0);
    stage("finalized");
  }
  await waitStatus(alice, id, (s) => s.phase === "Finalized", 120_000, "Finalized");
  await waitStatus(bob, id, (s) => s.phase === "Finalized", 120_000, "Finalized");

  // Alice (on move in game 0) forfeits one stake.
  const rec = recordOf("alice", id)!;
  expectFor(id, rec.me === 0 ? -STAKE : STAKE, ch);
  await noteErrors(id, "dispute");
  await waitSwept(id, "dispute");
  ch.done = true;
  save();
}

