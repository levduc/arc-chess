type TxRow = {
  hash: Hex;
  block: string;
  from: string;
  to: string;
  kind: string;
  channel: string | null;
  status: string;
  gasUsed: string;
  effectiveGasPrice: string;
  costWei: string;
  value: string;
};

async function blockscoutFrom(address: Address, fromBlock: bigint): Promise<Hex[]> {
  const base = `${EXPLORER}/api/v2/addresses/${address}/transactions?filter=from`;
  const out: Hex[] = [];
  let url = base;
  for (let page = 0; page < 50; page++) {
    const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!res.ok) throw new Error(`blockscout ${url}: ${res.status}`);
    const d = (await res.json()) as { items: Array<{ hash: Hex; block_number?: number; block?: number; from?: { hash: string } }>; next_page_params: Record<string, unknown> | null };
    for (const t of d.items) {
      const b = BigInt(t.block_number ?? t.block ?? 0);
      if (b >= fromBlock && t.from?.hash?.toLowerCase() === address.toLowerCase()) out.push(t.hash);
    }
    if (!d.next_page_params) break;
    url = `${base}&${new URLSearchParams(Object.entries(d.next_page_params).map(([k, v]) => [k, String(v)]))}`;
  }
  return out;
}

async function collect(): Promise<void> {
  if (!state.startBlock || !state.deployerBefore) throw new Error("no run to collect: state.json has no start block");
  const startBlock = BigInt(state.startBlock);

  // Who is who.
  const label = new Map<string, string>([[DEPLOYER.toLowerCase(), "deployer"], [HUB.toLowerCase(), "hub"], [USDC.toLowerCase(), "USDC"]]);
  const sessionOf = new Map<string, { name: Name; channel: Hex; kind: string }>();
  const walletOf = new Map<string, Name>();
  const kindOfChannel = new Map<string, ChannelKind>();
  for (const [k, ch] of Object.entries(state.channels) as Array<[ChannelKind, ChannelState]>) if (ch.id) kindOfChannel.set(ch.id.toLowerCase(), k);
  for (const n of NAMES) {
    const w = state.homes[n].wallet;
    if (!w) continue;
    label.set(w.toLowerCase(), `${n} wallet`);
    walletOf.set(w.toLowerCase(), n);
    for (const id of channelIdsOf(n)) {
      const r = recordOf(n, id);
      if (!r) continue;
      const s = r.signers[r.me].toLowerCase();
      const kind = kindOfChannel.get(id.toLowerCase()) ?? "?";
      label.set(s, `${n} session (${kind})`);
      sessionOf.set(s, { name: n, channel: id, kind });
    }
  }
  const senders = [...label.entries()].filter(([, l]) => l !== "hub" && l !== "USDC").map(([a]) => a as Address);

  // Every transaction each sender sent since the run started; Blockscout's list must match the sender's nonce.
  const hashes = new Map<Hex, string>();
  const nonceCheck: Array<{ sender: string; label: string; listed: number; nonceDelta: number; ok: boolean }> = [];
  for (const s of senders) {
    const nonceEnd = await pub.getTransactionCount({ address: s, blockTag: "latest" });
    const nonceStart = s === DEPLOYER.toLowerCase() ? (state.deployerNonceBefore ?? 0) : 0;
    let listed: Hex[] = [];
    for (let attempt = 0; attempt < 20; attempt++) {
      listed = await blockscoutFrom(s, startBlock);
      if (listed.length >= nonceEnd - nonceStart) break;
      await sleep(15_000);
    }
    // T5 review m-2: a short listing (Blockscout behind, or a transaction it never indexed) is a failed check, not a
    // quiet gap that only shows up later as a reconciliation that does not add up.
    nonceCheck.push({ sender: s, label: label.get(s)!, listed: listed.length, nonceDelta: nonceEnd - nonceStart, ok: listed.length === nonceEnd - nonceStart });
    for (const h of listed) hashes.set(h, s);
  }
  // Belt and braces: hashes the run recorded itself.
  for (const n of NAMES) {
    if (state.homes[n].fundTx) hashes.set(state.homes[n].fundTx!, DEPLOYER.toLowerCase());
    if (state.withdraws[n]) hashes.set(state.withdraws[n]!.txHash, state.homes[n].wallet!.toLowerCase());
  }

  const rows: TxRow[] = [];
  const payouts: Record<string, { deposits: Array<{ from: string; amount: string; hash: Hex }>; finalized?: { a: string; b: string; fee: string; hash: Hex; transfers: Array<{ to: string; amount: string }> }; owed: string[] }> = {};
  for (const hash of hashes.keys()) {
    const [tx, rc] = await Promise.all([pub.getTransaction({ hash }), pub.getTransactionReceipt({ hash })]);
    const from = tx.from.toLowerCase();
    const to = (tx.to ?? "").toLowerCase();
    let kind = "other";
    let channel: string | null = null;
    if (to === HUB.toLowerCase()) {
      try {
        const d = decodeFunctionData({ abi: channelHubAbi, data: tx.input });
        kind = d.functionName;
      } catch {
        kind = "hub (undecoded)";
      }
      for (const log of rc.logs) {
        if (log.address.toLowerCase() !== HUB.toLowerCase()) continue;
        try {
          const ev = decodeEventLog({ abi: channelHubAbi, data: log.data, topics: log.topics }) as { eventName: string; args: Record<string, unknown> };
          if (typeof ev.args.channelId === "string") channel = ev.args.channelId;
          if (ev.eventName === "PayoutDeferred") (payouts[channel ?? "?"] ??= { deposits: [], owed: [] }).owed.push(`${String(ev.args.to)} ${String(ev.args.amount)}`);
          if (ev.eventName === "Finalized" && channel) {
            const transfers: Array<{ to: string; amount: string }> = [];
            for (const l2 of rc.logs) {
              if (l2.address.toLowerCase() !== USDC.toLowerCase()) continue;
              try {
                const t = decodeEventLog({ abi: erc20Abi, data: l2.data, topics: l2.topics });
                if (t.eventName === "Transfer" && t.args.from.toLowerCase() === HUB.toLowerCase()) transfers.push({ to: t.args.to.toLowerCase(), amount: t.args.value.toString() });
              } catch {
                // not an ERC-20 event
              }
            }
            (payouts[channel] ??= { deposits: [], owed: [] }).finalized = {
              a: String(ev.args.balanceA),
              b: String(ev.args.balanceB),
              fee: String(ev.args.fee),
              hash,
              transfers,
            };
          }
          if (ev.eventName === "Deposited" && channel) {
            (payouts[channel] ??= { deposits: [], owed: [] }).deposits.push({ from, amount: String(ev.args.amount), hash });
          }
        } catch {
          // another event
        }
      }
    } else if (to === USDC.toLowerCase()) {
      try {
        kind = decodeFunctionData({ abi: erc20Abi, data: tx.input }).functionName;
        if (kind === "transfer" && walletOf.has(from)) kind = "withdraw (USDC transfer to the owner)";
      } catch {
        kind = "USDC (undecoded)";
      }
    } else if (tx.input === "0x" && tx.value > 0n) {
      if (from === DEPLOYER.toLowerCase() && walletOf.has(to)) kind = "fund agent (deployer -> wallet)";
      else if (walletOf.has(from) && sessionOf.has(to)) kind = "session top-up (wallet -> session key)";
      else if (sessionOf.has(from) && walletOf.has(to)) kind = "session sweep (session key -> wallet)";
      else kind = "native transfer";
    }
    if (!channel && sessionOf.has(from)) channel = sessionOf.get(from)!.channel;
    if (!channel && sessionOf.has(to)) channel = sessionOf.get(to)!.channel;
    const cost = rc.gasUsed * rc.effectiveGasPrice;
    rows.push({
      hash,
      block: rc.blockNumber.toString(),
      from: label.get(from) ?? from,
      to: label.get(to) ?? to,
      kind,
      channel: channel ? (kindOfChannel.get(channel.toLowerCase()) ?? channel) : null,
      status: rc.status,
      gasUsed: rc.gasUsed.toString(),
      effectiveGasPrice: rc.effectiveGasPrice.toString(),
      costWei: cost.toString(),
      value: tx.value.toString(),
    });
  }
  rows.sort((x, y) => (BigInt(x.block) < BigInt(y.block) ? -1 : BigInt(x.block) > BigInt(y.block) ? 1 : 0));

  // Balances now.
  const balances: Record<string, string> = {};
  for (const s of senders) balances[label.get(s)!] = (await nativeBalance(s)).toString();
  const owedNow: Record<string, string> = {};
  for (const s of senders) {
    const o = (await pub.readContract({ address: HUB, abi: channelHubAbi, functionName: "owed", args: [s] })) as bigint;
    if (o !== 0n) owedNow[label.get(s)!] = o.toString();
  }
  const committedEscrow = ((await pub.readContract({ address: HUB, abi: channelHubAbi, functionName: "committedEscrow" })) as bigint).toString();

  // The hardened hub's surface (audit M1, M2), simulated with eth_call -- nothing is sent. claim() takes no recipient
  // and pays msg.sender: with nothing owed it reverts NothingToClaim; renounceOwnership() always reverts.
  const simulate = async (from: Address, functionName: "claim" | "renounceOwnership"): Promise<string> => {
    try {
      // renounceOwnership is `pure` in the hardened hub (it only reverts), so it is read, not simulated.
      if (functionName === "renounceOwnership") await pub.readContract({ account: from, address: HUB, abi: channelHubAbi, functionName });
      else await pub.simulateContract({ account: from, address: HUB, abi: channelHubAbi, functionName });
      return "succeeded";
    } catch (err) {
      const name = (err as { cause?: { data?: { errorName?: string } } }).cause?.data?.errorName;
      return name ? `reverted ${name}` : `reverted (${String(err).split("\n")[0].slice(0, 120)})`;
    }
  };
  const hardening: Array<{ check: string; got: string; ok: boolean }> = [];
  for (const s of senders.filter((x) => !sessionOf.has(x))) {
    const got = await simulate(s, "claim");
    hardening.push({ check: `claim() from ${label.get(s)}`, got, ok: got === "reverted NothingToClaim" });
  }
  const renounce = await simulate(DEPLOYER, "renounceOwnership");
  hardening.push({ check: "renounceOwnership() from the owner (deployer)", got: renounce, ok: renounce === "reverted RenounceDisabled" });

  // Hub-side checks: deposits of deposit + fee each, payouts exactly as expected, the fee to the deployer.
  const hubChecks: Array<{ channel: string; check: string; want: string; got: string; ok: boolean }> = [];
  for (const [kind, ch] of Object.entries(state.channels) as Array<[ChannelKind, ChannelState]>) {
    if (!ch.id) continue;
    const p = payouts[ch.id];
    const rec = recordOf("alice", ch.id)!;
    const [p0, p1] = rec.participants.map((a) => a.toLowerCase());
    const id = ch.id;
    const params = (await read(() => pub.readContract({ address: HUB, abi: channelHubAbi, functionName: "channelParams", args: [id] }))) as { feePerPlayer: bigint; feeRecipient: Address };
    const add = (check: string, want: string, got: string) => hubChecks.push({ channel: kind, check, want, got, ok: want === got });
    // T5 review m-1: every expectation is the script's own (the deploy's fee, the scripted results, the deployer as fee
    // recipient), never read back from the hub, so a hub with another fee or recipient fails here.
    add("channel's fee per player (the deploy's)", FEE_PER_PLAYER.toString(), params.feePerPlayer.toString());
    add("channel's fee recipient (the deployer)", DEPLOYER.toLowerCase(), params.feeRecipient.toLowerCase());
    add("deposits", `2 x ${DEPOSIT + FEE_PER_PLAYER}`, `${p?.deposits.length ?? 0} x ${[...new Set(p?.deposits.map((d) => d.amount) ?? [])].join("/")}`);
    add("Finalized.balanceA (participant 0)", ch.expectedA ?? "?", p?.finalized?.a ?? "none");
    add("Finalized.balanceB (participant 1)", ch.expectedB ?? "?", p?.finalized?.b ?? "none");
    add("Finalized.fee", (2n * FEE_PER_PLAYER).toString(), p?.finalized?.fee ?? "none");
    const tr = (who: string) => p?.finalized?.transfers.filter((t) => t.to === who).map((t) => t.amount).join("+") || "none";
    add("USDC transfer hub -> participant 0", ch.expectedA ?? "?", tr(p0));
    add("USDC transfer hub -> participant 1", ch.expectedB ?? "?", tr(p1));
    add("USDC transfer hub -> fee recipient (deployer)", (2n * FEE_PER_PLAYER).toString(), tr(DEPLOYER.toLowerCase()));
    add("PayoutDeferred events", "0", String(p?.owed.length ?? 0));
  }

  // Wallet-side reconciliation, per home, to the wei: funding + payouts - deposits - withdrawn - every gas the home
  // paid (wallet and session keys) = the wallet's balance + its session keys' balances now.
  const recon: Array<Record<string, string | boolean>> = [];
  const rowsFrom = (pred: (r: TxRow) => boolean) => rows.filter(pred);
  for (const n of NAMES) {
    const w = state.homes[n].wallet!.toLowerCase();
    const mine = (lbl: string) => lbl === `${n} wallet` || lbl.startsWith(`${n} session`);
    const gas = rowsFrom((r) => mine(r.from)).reduce((a, r) => a + BigInt(r.costWei), 0n);
    const funded = rowsFrom((r) => r.kind.startsWith("fund agent") && r.to === `${n} wallet`).reduce((a, r) => a + BigInt(r.value), 0n);
    let paidIn = 0n;
    let deposited = 0n;
    for (const p of Object.values(payouts)) {
      for (const t of p.finalized?.transfers ?? []) if (t.to === w) paidIn += BigInt(t.amount) * WEI_PER_UNIT;
      for (const d of p.deposits) if (d.from === w) deposited += BigInt(d.amount) * WEI_PER_UNIT;
    }
    const withdrawn = parseUnits(state.withdraws[n]?.amount ?? "0", 6) * WEI_PER_UNIT;
    const expected = funded + paidIn - deposited - withdrawn - gas;
    let held = 0n;
    for (const [lbl, bal] of Object.entries(balances)) if (mine(lbl)) held += BigInt(bal);
    recon.push({
      home: n,
      funded: funded.toString(),
      payoutsIn: paidIn.toString(),
      depositsOut: deposited.toString(),
      withdrawn: withdrawn.toString(),
      gasPaid: gas.toString(),
      expectedHeld: expected.toString(),
      held: held.toString(),
      ok: expected === held,
    });
  }
  const totalGas = rows.reduce((a, r) => a + BigInt(r.costWei), 0n);
  let heldAll = 0n;
  for (const b of Object.values(balances)) heldAll += BigInt(b);
  const system = {
    deployerBefore: state.deployerBefore,
    deployerAfter: balances.deployer,
    heldByAgentsAfter: (heldAll - BigInt(balances.deployer)).toString(),
    totalGas: totalGas.toString(),
    check: `${state.deployerBefore} = deployerAfter + agents + gas`,
    ok: BigInt(state.deployerBefore) === heldAll + totalGas,
    residual: (BigInt(state.deployerBefore) - heldAll - totalGas).toString(),
  };

  const result = { generatedAt: new Date().toISOString(), hub: HUB, rules: RULES, startBlock: state.startBlock, endBlock: state.endBlock, nonceCheck, rows, balances, owedNow, committedEscrow, hubChecks, hardening, recon, system, channels: state.channels, measures: state.measures, notes: state.notes, withdraws: state.withdraws, spawns: state.spawns ?? [], rateLimited: state.rateLimited ?? {} };
  writeFileSync(join(DIR, "result.json"), `${JSON.stringify(result, (_k, v) => (typeof v === "bigint" ? v.toString() : v), 2)}\n`);
  writeFileSync(join(DIR, "report-fragment.md"), fragment(result));
  progress("collected", { txs: rows.length, totalGasUsdc: formatUnits(totalGas, 18), systemOk: system.ok, reconOk: recon.every((r) => r.ok), hubOk: hubChecks.every((c) => c.ok), hardeningOk: hardening.every((c) => c.ok), nonceOk: nonceCheck.every((c) => c.ok) });
}

const usdc18 = (wei: string | bigint) => formatUnits(BigInt(wei), 18);
const gwei = (wei: string) => formatUnits(BigInt(wei), 9);

function fragment(r: any): string {
  const L: string[] = [];
  L.push("### Transactions", "", "| # | Action | Channel | From | Tx | Gas used | Price (gwei) | Cost (USDC) |", "|---|---|---|---|---|---|---|---|");
  r.rows.forEach((x: TxRow, i: number) => {
    L.push(`| ${i + 1} | ${x.kind}${x.status === "success" ? "" : ` (**${x.status}**)`} | ${x.channel ?? ""} | ${x.from} | [\`${x.hash.slice(0, 10)}…\`](${EXPLORER}/tx/${x.hash}) | ${Number(x.gasUsed).toLocaleString("en-US")} | ${gwei(x.effectiveGasPrice)} | ${usdc18(x.costWei)} |`);
  });
  L.push("", "Full hashes:", "");
  r.rows.forEach((x: TxRow, i: number) => L.push(`${i + 1}. ${x.kind}: ${EXPLORER}/tx/${x.hash}`));
  const byKind = new Map<string, TxRow[]>();
  for (const x of r.rows as TxRow[]) byKind.set(x.kind, [...(byKind.get(x.kind) ?? []), x]);
  L.push("", "### Cost per action", "", "| Action | Count | Gas used (min–max) | Cost per action, USDC (min–max) | Total, USDC |", "|---|---|---|---|---|");
  for (const [k, xs] of byKind) {
    const g = xs.map((x) => BigInt(x.gasUsed));
    const c = xs.map((x) => BigInt(x.costWei));
    const min = (a: bigint[]) => a.reduce((p, v) => (v < p ? v : p));
    const max = (a: bigint[]) => a.reduce((p, v) => (v > p ? v : p));
    L.push(`| ${k} | ${xs.length} | ${min(g).toLocaleString("en-US")}–${max(g).toLocaleString("en-US")} | ${usdc18(min(c))}–${usdc18(max(c))} | ${usdc18(c.reduce((a, v) => a + v, 0n))} |`);
  }
  L.push("", "### Hub-side checks (6-decimal base units)", "", "| Channel | Check | Expected | Got | OK |", "|---|---|---|---|---|");
  for (const c of r.hubChecks) L.push(`| ${c.channel} | ${c.check} | ${c.want} | ${c.got} | ${c.ok ? "yes" : "**NO**"} |`);
  L.push("", "### Hardened-hub surface (eth_call simulations, nothing sent)", "", "| Check | Got | OK |", "|---|---|---|");
  for (const c of r.hardening ?? []) L.push(`| ${c.check} | ${c.got} | ${c.ok ? "yes" : "**NO**"} |`);
  L.push("", "### Wallet-side reconciliation (wei, 18 decimals)", "", "| Home | Funded | Payouts in | Deposits out | Withdrawn | Gas paid | Expected held | Held | OK |", "|---|---|---|---|---|---|---|---|---|");
  for (const x of r.recon) L.push(`| ${x.home} | ${x.funded} | ${x.payoutsIn} | ${x.depositsOut} | ${x.withdrawn} | ${x.gasPaid} | ${x.expectedHeld} | ${x.held} | ${x.ok ? "yes" : "**NO**"} |`);
  L.push("", `System: deployer before ${usdc18(r.system.deployerBefore)} = deployer after ${usdc18(r.system.deployerAfter)} + held by agents ${usdc18(r.system.heldByAgentsAfter)} + gas ${usdc18(r.system.totalGas)} → ${r.system.ok ? "exact" : `**off by ${r.system.residual} wei**`}.`);
  L.push("", "### Balances after (native, 18 decimals)", "", "| Address | Balance (USDC) |", "|---|---|");
  for (const [k, v] of Object.entries(r.balances)) L.push(`| ${k} | ${usdc18(v as string)} |`);
  L.push("", "### Sender nonce check (Blockscout listing vs nonce)", "", "| Sender | Listed | Nonce delta | OK |", "|---|---|---|---|");
  for (const x of r.nonceCheck) L.push(`| ${x.label} | ${x.listed} | ${x.nonceDelta} | ${x.ok ? "yes" : "**NO**"} |`);
  L.push("", "### Checkout at each spawn", "", "| Process | At | Checkout |", "|---|---|---|");
  for (const x of r.spawns ?? []) L.push(`| ${x.label} | ${x.at} | ${x.checkout} |`);
  L.push("", "### Timings", "", "| Step | Seconds | Note |", "|---|---|---|");
  for (const m of r.measures as Measure[]) L.push(`| ${m.step} | ${(m.ms / 1000).toFixed(1)} | ${m.note ?? ""} |`);
  return `${L.join("\n")}\n`;
}

