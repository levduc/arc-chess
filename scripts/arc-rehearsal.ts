async function channelXmtp(): Promise<void> {
  const ch = (state.channels.xmtp ??= { startedAt: new Date().toISOString(), notes: [] });
  const alice = player("alice");
  const bob = player("bob");
  const id = await openChannel(ch, "xmtp", NORMAL_TIMEOUT);
  const stage = (s: string) => {
    ch.stage = s;
    save();
    progress("xmtp stage", { stage: s });
  };

  if (!ch.stage) {
    await waitTransport(alice, id, "relay", 90_000);
    await waitTransport(bob, id, "relay", 90_000);
    // Both session keys must be registered on XMTP dev before the host goes down, or there is nothing to fall back to.
    const t0 = Date.now();
    let ready = true;
    for (const n of NAMES) {
      const r = recordOf(n, id)!;
      const signer = r.signers[r.me];
      try {
        const inbox = await waitFor(`${n}'s session key ${signer} registered on XMTP dev`, 300_000, async () => {
          const st = await xmtpInbox(signer);
          return st.inboxId ? st : undefined;
        }, 5_000);
        progress("xmtp inbox", { name: n, signer, inboxId: inbox.inboxId, installations: inbox.installations });
      } catch (err) {
        ready = false;
        ch.notes.push(`FAILED: ${String(err)}`);
        progress("xmtp inbox", { name: n, signer, error: String(err) });
      }
    }
    measure("xmtp: channel Open -> both session keys registered on XMTP dev", Date.now() - t0);
    // Three moves over the relay, then the host dies.
    const t = await playFrom(alice, bob, id, SCHOLARS_MATE, 0, { upTo: 3 });
    measure("xmtp: 3 moves over the relay (sum)", sum(t), `per move ms: ${t.join(", ")}`);
    stage(ready ? "relay-moves" : "not-registered");
  }
  if (ch.stage === "not-registered") {
    ch.failed = "the session keys were not registered on XMTP dev: the host was NOT killed; the game finished over the relay";
    const t = await playFrom(alice, bob, id, SCHOLARS_MATE, 0);
    measure("xmtp: (fallback) remaining moves over the relay (sum)", sum(t));
    stage("played");
  }
  if (ch.stage === "relay-moves") {
    const killedAt = Date.now();
    const killed = state.pids.server;
    await stopPid("server (mid-game kill)", killed, marksOf("server"), "SIGKILL");
    // T5 review I-2: the pid is dead now and may be reused; nothing may signal it again.
    delete state.pids.server;
    save();
    progress("host killed", { pid: typeof killed === "object" ? killed.pid : killed });
    stage("host-killed");
    try {
      await waitTransport(alice, id, "xmtp", 90_000);
      await waitTransport(bob, id, "xmtp", 90_000);
      measure("xmtp: host SIGKILL -> both daemons on transport xmtp (polled every 2 s)", Date.now() - killedAt);
    } catch (err) {
      ch.notes.push(`switch to xmtp not seen: ${String(err)}`);
    }
  }
  if (ch.stage === "host-killed") {
    try {
      const t = await playFrom(alice, bob, id, SCHOLARS_MATE, 0, { ms: 240_000 });
      measure("xmtp: remaining moves with the host down, over XMTP dev (sum)", sum(t), `per move ms: ${t.join(", ")}`);
      stage("played");
    } catch (err) {
      ch.failed = `the game did not finish over XMTP: ${String(err)}; the host was restarted to finish over the relay`;
      save();
      progress("xmtp failed", { error: String(err) });
      await startServer();
      await waitTransport(alice, id, "relay", 120_000);
      await waitTransport(bob, id, "relay", 120_000);
      await playFrom(alice, bob, id, SCHOLARS_MATE, 0);
      stage("played");
    }
  }
  const s = await waitGameOver(alice, bob, id, "white_won", 240_000);
  const w = winnerOf(s);
  ch.games = [{ gameIndex: 0, result: s.gameStatus, winner: w }];
  expectFor(id, w === 0 ? STAKE : -STAKE, ch);

  const sa = await status(alice, id);
  const sb = await status(bob, id);
  progress("xmtp: closing", { aliceTransport: sa.transport, bobTransport: sb.transport });
  ch.notes.push(`close sent with transports alice=${sa.transport} bob=${sb.transport}`);
  await closeBoth(alice, bob, id, "xmtp", 300_000);
  await noteErrors(id, "xmtp");
  await waitSwept(id, "xmtp");
  ch.done = true;
  save();
}

