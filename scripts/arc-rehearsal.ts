const XMTP_HELPER = `
const [address] = process.argv.slice(2);
const sdk = await import(process.env.XMTP_SDK_URL);
const backend = await sdk.createBackend({ env: "dev" });
const inboxId = await sdk.getInboxIdForIdentifier(backend, { identifier: address.toLowerCase(), identifierKind: sdk.IdentifierKind.Ethereum });
if (!inboxId) { process.stdout.write(JSON.stringify({ inboxId: null, installations: 0 }) + "\\n"); process.exit(0); }
const [st] = await sdk.Client.fetchInboxStates([inboxId], backend);
process.stdout.write(JSON.stringify({ inboxId, installations: st?.installations?.length ?? 0 }) + "\\n");
process.exit(0);
`;

/** A short-lived child process reads `address`'s XMTP inbox on the dev network (no client of its own). */
function xmtpInbox(address: Address): Promise<{ inboxId: string | null; installations: number }> {
  const helper = join(DIR, "xmtp-helper.mjs");
  if (!existsSync(helper)) writeFileSync(helper, XMTP_HELPER);
  const sdkEntry = join(state.homes.alice.home, "xmtp/sdk/node_modules/@xmtp/node-sdk/dist/index.js");
  return new Promise((resolvePromise, reject) => {
    const child = spawn(process.execPath, [helper, address], {
      env: childEnv(undefined, { XMTP_SDK_URL: pathToFileURL(sdkEntry).href }),
      stdio: ["ignore", "pipe", "pipe"],
    });
    let out = "";
    let err = "";
    const timer = setTimeout(() => child.kill("SIGKILL"), 60_000);
    child.stdout.on("data", (c: Buffer) => (out += c.toString("utf8")));
    child.stderr.on("data", (c: Buffer) => (err += c.toString("utf8")));
    child.once("close", (code) => {
      clearTimeout(timer);
      const line = out.trim().split("\n").at(-1);
      if (code === 0 && line) {
        try {
          resolvePromise(JSON.parse(line) as { inboxId: string | null; installations: number });
          return;
        } catch {
          // fall through
        }
      }
      reject(new Error(`xmtp helper failed (exit ${code}): ${err.slice(-800)}`));
    });
  });
}

