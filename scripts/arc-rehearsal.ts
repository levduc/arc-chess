async function isPortFree(port: number): Promise<boolean> {
  return new Promise((r) => {
    const srv = createServer();
    srv.once("error", () => r(false));
    srv.listen(port, "127.0.0.1", () => srv.close(() => r(true)));
  });
}

/** A child's environment (T5 review I-1): an allowlist of this process's variables (`arc-rehearsal-lib.ts`), never
 *  the whole of it, plus the fake `HOME`, npm's cache and, for an `arena` process, its `ARENA_HOME`. */
function childEnv(home?: string, extra: Record<string, string> = {}): NodeJS.ProcessEnv {
  return allowlistedEnv(process.env, { HOME: FAKE_HOME, npm_config_cache: NPM_CACHE, ARENA_HOME: home, ...extra });
}

/** Runs one `arena` command to completion; output goes to `logs/cli.log` too (the CLI never prints a key). */
function runCli(name: Name, args: string[], timeoutMs = 180_000): Promise<{ status: number; stdout: string; stderr: string }> {
  const home = state.homes[name].home;
  return new Promise((resolvePromise, reject) => {
    const child = spawn(process.execPath, [CLI_BIN, ...args], { cwd: REPO_ROOT, env: childEnv(home), stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    const timer = setTimeout(() => {
      stderr += `\n[rehearsal] killed after ${timeoutMs} ms`;
      child.kill("SIGKILL");
    }, timeoutMs);
    child.stdout.on("data", (c: Buffer) => (stdout += c.toString("utf8")));
    child.stderr.on("data", (c: Buffer) => (stderr += c.toString("utf8")));
    child.once("error", (e) => {
      clearTimeout(timer);
      reject(e);
    });
    child.once("close", (code) => {
      clearTimeout(timer);
      appendFileSync(join(LOGS, "cli.log"), `\n$ [${name}] arena ${args.join(" ")}\n(exit ${code})\n--- stdout\n${stdout}\n--- stderr\n${stderr}\n`);
      resolvePromise({ status: code ?? 1, stdout, stderr });
    });
  });
}

/** Runs a command that prints JSON. `retryRateLimit` (only for commands that are safe to repeat: init, owner set,
 *  xmtp enable, sweep) retries one the public RPC rate-limited (HTTP 429 / -32005), up to 6 times, 20 s apart. */
async function cliJson(name: Name, args: string[], timeoutMs?: number, retryRateLimit = false): Promise<any> {
  for (let attempt = 1; ; attempt++) {
    const r = await runCli(name, args, timeoutMs);
    if (r.status === 0) return JSON.parse(r.stdout);
    const why = (r.stderr || r.stdout).slice(-1500);
    if (retryRateLimit && attempt < 6 && /status 429|rate limit/i.test(why)) {
      state.notes.push(`[${name}] arena ${args[0]} was rate-limited by the RPC (attempt ${attempt}); retried`);
      progress("rate limited", { name, cmd: args[0], attempt });
      await sleep(20_000);
      continue;
    }
    throw new Error(`[${name}] arena ${args.join(" ")} failed (exit ${r.status}): ${why}`);
  }
}

/** The checkout's HEAD and its uncommitted source files right now: other agents commit to this checkout while a run
 *  is going, and a child runs whatever is on disk when it is spawned. */
function checkoutNow(): string {
  // trimEnd, not trim: porcelain lines start with a status column that may be a space.
  const git = (args: string[]) => spawnSync("git", args, { cwd: REPO_ROOT, encoding: "utf8" }).stdout.trimEnd();
  const dirty = git(["status", "--porcelain", "--", "packages", "apps", "contracts/src", "scripts"])
    .split("\n")
    .filter(Boolean)
    .map((l) => l.slice(3));
  return `${git(["rev-parse", "--short", "HEAD"])}${dirty.length > 0 ? ` + uncommitted: ${dirty.join(", ")}` : ""}`;
}

/** Starts a detached long-lived child (its own process group), logging to `logs/<label>.log`. */
function spawnDetached(label: string, args: string[], env: NodeJS.ProcessEnv): ChildProcess {
  const checkout = checkoutNow();
  state.spawns = [...(state.spawns ?? []), { label, at: new Date().toISOString(), checkout }];
  save();
  progress("spawn", { label, checkout });
  const fd = openSync(join(LOGS, `${label}.log`), "a");
  const child = spawn(process.execPath, args, { cwd: REPO_ROOT, env, stdio: ["ignore", fd, fd], detached: true });
  child.unref();
  return child;
}

/** The command-line strings that identify each detached process of this run (with its start time: `isOurs`). */
function marksOf(label: "server" | Name): string[] {
  return label === "server" ? [SERVER_BIN, serverConfigPath()] : [CLI_BIN, "daemon"];
}

/** The pid and start time of a process just spawned; the start time is read from /proc, retried briefly. */
async function entryOf(child: ChildProcess, label: string): Promise<ProcEntry> {
  for (let i = 0; i < 40 && child.pid !== undefined; i++) {
    const startTime = procStartTime(child.pid);
    if (startTime !== null) return { pid: child.pid, startTime };
    await sleep(25);
  }
  throw new Error(`cannot read the start time of ${label} (pid ${child.pid}) from /proc: it could not be stopped safely later`);
}

/** Signals `entry` only while it is still the process this script started (pid, start time and command line: T5
 *  review I-2), then waits until it is gone; SIGKILL after `graceMs`. Anything else is left alone, and logged. */
async function stopPid(label: string, entry: ProcEntry | number | undefined, marks: string[], signal: NodeJS.Signals = "SIGTERM", graceMs = 30_000): Promise<void> {
  if (entry === undefined) return;
  if (!isOurs(entry, marks)) {
    progress("stop", { what: label, entry, skipped: "not this run's process (gone, or the pid was reused): not signalled" });
    return;
  }
  const { pid } = entry as ProcEntry;
  progress("stop", { what: label, pid, signal });
  process.kill(pid, signal);
  const end = Date.now() + graceMs;
  while (isOurs(entry, marks) && Date.now() < end) await sleep(200);
  if (isOurs(entry, marks)) {
    progress("stop", { what: label, pid, signal: "SIGKILL", why: `still alive after ${graceMs} ms` });
    process.kill(pid, "SIGKILL");
    while (isOurs(entry, marks)) await sleep(200);
  }
}

/** Refuses to start over a process an earlier run left running (resume: see the header), by its pid and start time. */
function refuseIfLeftRunning(label: "server" | Name): void {
  const entry = state.pids[label];
  if (isOurs(entry, marksOf(label))) {
    throw new Error(`${label} from an earlier run is still running (pid ${(entry as ProcEntry).pid}); stop it first: kill ${(entry as ProcEntry).pid}`);
  }
}

async function waitHttp(url: string, what: string, ms = 60_000): Promise<void> {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try {
      const r = await fetch(url, { signal: AbortSignal.timeout(3_000) });
      if (r.ok) return;
    } catch {
      // not up yet
    }
    await sleep(300);
  }
  throw new Error(`${what} did not answer ${url} within ${ms} ms`);
}

