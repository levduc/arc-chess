/**
 * `pnpm exec tsx scripts/arc-rehearsal.ts --dir PATH [--collect-only] [--start-block N]`
 *
 * Plan 6 Task 5 (spec §4): the Arc TESTNET dress rehearsal with real (faucet) USDC, against the deployment in
 * `contracts/deployments/5042002.json`. It never deploys. In order:
 *
 *  1. Preflight: `eth_chainId` must be 5042002 (Arc testnet; mainnet is 5042 and is refused), the hub, rules and USDC
 *     must hold code, and the configured ports must be free.
 *  2. A local host server (`apps/server`) on 127.0.0.1:8760, configured for Arc testnet: chainId 5042002,
 *     `rpcUrl`/`publicRpcUrl` = the testnet RPC, `xmtp: {env: "dev"}`, an `audit` text that says what this is, and the
 *     indexer starting at the hub's deploy block (read from Deploy.s.sol's broadcast record, or `--start-block`) in
 *     10,000-block chunks. Daemons and indexer poll every 3 s: the public
 *     testnet RPC rate-limits.
 *  3. Two agent homes (`alice`, `bob`), each written by `arena init --server` only (the wallet key is generated by
 *     `init`), with `arena owner set <deployer>`, `arena xmtp enable` (one real install per home, sharing npm's
 *     cache), `--min-challenge-timeout 300` (testnet only: the dispute channel's offer uses 300 s; the other channels
 *     ask for the default 900 s explicitly) and daemon API ports 8761/8762.
 *  4. The deployer funds each wallet with 2 USDC (a native transfer: on Arc, USDC is the gas token and one balance).
 *  5. Three channels, strictly one after the other (the next opens only once both session keys of the previous one
 *     are swept), each deposit 1 USDC, stake 0.1 USDC:
 *     - `normal`: three games (a win, a win as black, a draw by agreement), then a cooperative close;
 *     - `dispute`: Alice challenges, Bob answers with a move (respond), Bob challenges, Alice does not move, and the
 *       watchtower times it out (challengeTimeout 300 s);
 *     - `xmtp`: the host server is SIGKILLed mid-game; both daemons switch to XMTP `dev`, finish the game and close
 *       over it.
 *  6. `arena sweep` and `arena withdraw --all` in each home (withdraw pays only the owner, the deployer).
 *  7. Collection: every transaction sent by the deployer, the two wallets and the six session keys during the run
 *     (Blockscout's address listing, checked against each sender's nonce), each receipt's gasUsed x
 *     effectiveGasPrice, the hub-side payouts against the expected ones, and a wallet-side reconciliation to the wei.
 *     Written to `<dir>/result.json` and `<dir>/report-fragment.md`.
 *
 * Safety:
 * - The RPC is hard-coded to Arc testnet, and `eth_chainId` is asserted to be 0x4cef52 before every transaction the
 *   deployer signs. Every agent transaction is signed by the daemons, whose homes `init` bound to chain 5042002.
 * - The deployer key is read from `~/.config/arena-deploy/arc-testnet-deployer.json` (`data`, or the `data[]` entry
 *   whose `address` is the deployer's) into this process's memory,
 *   only in the funding step. It is never printed, logged, written anywhere or passed to a child process.
 * - Every child process runs with `HOME` and `ARENA_HOME` under `--dir`. The server and daemons are started detached,
 *   so a crash of this script leaves the watchtowers running; their pids are in `<dir>/state.json`, and only those
 *   pids are ever signalled.
 * - Between channels, the closed-system total (deployer + wallets + session keys; fees go back to the deployer, the
 *   fee recipient) may fall only by gas. The run stops if that exceeds 2 USDC.
 * - Children never inherit this process's whole environment, only an allowlist (`arc-rehearsal-lib.ts`: `PATH`, the
 *   locale, proxies, `NODE_*`, …). A key exported in the operator's shell never reaches a daemon, the server or the
 *   `npm install` that `arena xmtp enable` runs.
 * - Each detached process is recorded with its pid and start time, and is signalled only while both still match
 *   (and its command line is this run's), so a pid the kernel reused is never touched.
 *
 * Resume: `state.json` records the steps done, so a rerun with the same `--dir` resumes after the last completed step.
 * A run that stops leaves the server and daemons running on purpose, so the watchtowers keep watching. Before resuming,
 * stop them by the pids in `state.json` (`kill <pid>`, once no channel needs them). The rerun refuses to start over one
 * that is still running, and its message names the pid. A channel step that was half done resumes from the chain and
 * the daemons' state. One that cannot, such as an offer posted with no channel recorded, stops with "settle it by hand".
 */
