function parseArgs(argv: string[]): { dir: string; collectOnly: boolean; startBlock?: string } {
  let dir: string | undefined;
  let collectOnly = false;
  let startBlock: string | undefined;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--dir") dir = argv[++i];
    else if (argv[i] === "--collect-only") collectOnly = true;
    else if (argv[i] === "--start-block") startBlock = argv[++i];
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  if (!dir) throw new Error("usage: tsx scripts/arc-rehearsal.ts --dir PATH [--collect-only] [--start-block N]");
  if (startBlock !== undefined && !/^[0-9]+$/.test(startBlock)) throw new Error("--start-block must be a block number");
  return { dir: resolve(dir), collectOnly, ...(startBlock !== undefined ? { startBlock } : {}) };
}

